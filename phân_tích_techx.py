def plot_rate(ax, data, col, min_n=50, order=None):
    g = data.groupby(col).da_chot.agg(['sum', 'count']); g = g[g['count'] >= min_n]
    g['rate'] = g['sum'] / g['count']
    ci = [proportion_confint(s, n, method='wilson') for s, n in zip(g['sum'], g['count'])]
    g['lo'], g['hi'] = [c[0] for c in ci], [c[1] for c in ci]
    g = g.sort_values('rate', ascending=False)
    ax.bar(g.index, g.rate, yerr=[g.rate - g.lo, g.hi - g.rate], capsize=4)
    ax.axhline(data.da_chot.mean(), color='red', ls='--', lw=1, label='Trung bình chung')
    ax.set_title(f'Tỷ lệ chốt theo {col}'); ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda v,_: f'{v:.0%}'))
    for i, (n, r) in enumerate(zip(g['count'], g.rate)): ax.text(i, r, f'n={n:,}', ha='center', va='bottom', fontsize=8)
    ax.tick_params(axis='x', rotation=20); ax.legend()
    return g

