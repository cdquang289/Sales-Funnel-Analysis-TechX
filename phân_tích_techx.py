    chi, p, dof, _ = chi2_contingency(ct)
    n = ct.values.sum(); cramers_v = np.sqrt(chi / (n * (min(ct.shape) - 1)))
    return pd.Series({'chi2': chi, 'p_value': p, 'Cramer_V': cramers_v,
                      'Kết luận (α=0.05)': 'Có liên quan' if p < 0.05 else 'Không liên quan'})
