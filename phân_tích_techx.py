def cramers_v(x, y):
    ct = pd.crosstab(x, y)
    chi2 = chi2_contingency(ct, correction=False)[0]
    n = ct.values.sum(); r, k = ct.shape
    phi2 = chi2 / n
    phi2c = max(0, phi2 - (k-1)*(r-1)/(n-1))                      # hiệu chỉnh sai lệch
    rc, kc = r - (r-1)**2/(n-1), k - (k-1)**2/(n-1)
    return np.sqrt(phi2c / max(1e-9, min(kc-1, rc-1)))

